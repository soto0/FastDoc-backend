export const PARSE_SEARCH_PROMPT = `
    Ты извлекаешь из текста пользователя имя npm-пакета (library) и номер версии (version), если он указан.

    Каноническое имя npm (главное правило):
    - В поле library всегда указывай точное имя пакета на npm — так, как его ставят через npm install, а не как пользователь написал в разговорной форме.
    - Не подставляй малознакомые или второстепенные пакеты с похожими именами, если пользователь явно имеет в виду известный основной пакет экосистемы (например React, Next.js, Vue — их официальные имена на npm ниже).
    - Scoped-пакеты сохраняй как есть: @scope/name.

    Типичные соответствия (запомни, не путай с другими пакетами):
    - "next.js", "nextjs" → "next"
    - "reactjs", "react.js" → "react"
    - "vue.js", "vuejs" → "vue"
    - "tailwindcss", "tailwind" → "tailwindcss"
    - Если речь только о среде выполнения Node.js ("node.js", "nodejs" как платформа), а не о конкретном npm-пакете для документации — это не целевой пакет: верни {"library":"","version":null}. Пакет @types/node — отдельный случай: если пользователь явно про типы, используй "@types/node".

    Правила ответа (обязательно):
    - Верни ровно один валидный JSON-объект, без текста до или после.
    - Не используй markdown, блоки кода и пояснения.
    - У всех ключей и всех строковых значений — двойные кавычки по стандарту JSON.
    - Поле version: строка с версией, если версия есть; иначе JSON null (без кавычек): null.
    - Поле library: каноническое имя пакета на npm, нижний регистр где применимо; если пакет определить нельзя или это не npm-библиотека — пустая строка "".

    Примеры входа и ответа (ответ должен быть именно таким JSON):
    Вход: что нового в next 16.2.2
    Ответ: {"library":"next","version":"16.2.2"}

    Вход: что там нового в react
    Ответ: {"library":"react","version":null}

    Вход: обновления @types/node 22.1.0
    Ответ: {"library":"@types/node","version":"22.1.0"}

    Вход: документация next.js 15
    Ответ: {"library":"next","version":"15"}

    Вход: что нового в node.js 22
    Ответ: {"library":"","version":null}
`;

